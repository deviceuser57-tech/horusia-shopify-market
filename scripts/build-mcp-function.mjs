// Bundles src/lib/mcp/index.ts into a self-contained Supabase Edge Function
// at supabase/functions/mcp/index.ts.
//
// Why this exists: @lovable.dev/mcp-js's mcpPlugin() externalizes the MCP
// entry as `npm:D:\...` on Windows (its bare-specifier check only skips
// paths starting with "." or "/"), producing a function that cannot deploy.
// This script performs the same bundling the plugin intends, with correct
// npm: specifiers. Run via `npm run mcp:bundle` (also runs after `npm run build`).
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// Minimal .env loader for VITE_* values inlined into the Deno bundle.
const env = {};
try {
  for (const line of readFileSync(resolve(root, ".env"), "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
    if (m && !line.trimStart().startsWith("#")) {
      env[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  }
} catch {
  // no .env — import.meta.env values will be undefined in the bundle
}

const pkg = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
// Pin npm: specifiers to the actually-installed version, not the semver range.
const depVersion = (name) => {
  try {
    return JSON.parse(readFileSync(resolve(root, "node_modules", name, "package.json"), "utf8")).version;
  } catch {
    return (pkg.dependencies?.[name] ?? pkg.devDependencies?.[name] ?? "").replace(/^[\^~]/, "");
  }
};

const npmSpecifier = (id) => {
  if (id === "@lovable.dev/mcp-js" || id.startsWith("@lovable.dev/mcp-js/")) {
    const sub = id.slice("@lovable.dev/mcp-js".length);
    return `npm:@lovable.dev/mcp-js@${depVersion("@lovable.dev/mcp-js")}${sub}`;
  }
  if (id === "@supabase/supabase-js" || id.startsWith("@supabase/supabase-js/")) {
    const sub = id.slice("@supabase/supabase-js".length);
    return `npm:@supabase/supabase-js@${depVersion("@supabase/supabase-js")}${sub}`;
  }
  if (id === "zod" || id.startsWith("zod/")) {
    const sub = id.slice("zod".length);
    return `npm:zod@${depVersion("zod")}${sub}`;
  }
  return null;
};

const externalize = {
  name: "externalize-npm",
  setup(pluginBuild) {
    pluginBuild.onResolve({ filter: /.*/ }, (args) => {
      if (args.path.startsWith(".") || args.path.startsWith("/") || /^[A-Za-z]:[\\/]/.test(args.path)) {
        return null;
      }
      const spec = npmSpecifier(args.path);
      if (spec) return { path: spec, external: true };
      // Any other bare import: leave for esbuild to resolve or fail loudly.
      return null;
    });
  },
};

const mcpEntryAbs = resolve(root, "src/lib/mcp/index.ts");
const wrapper = `import mcp from ${JSON.stringify(mcpEntryAbs)};\nimport { createSupabaseHandler } from "@lovable.dev/mcp-js/stacks/supabase";\nDeno.serve(createSupabaseHandler(mcp, { functionName: "mcp" }));\n`;

const defines = {
  "import.meta.env": JSON.stringify(env),
};
for (const key of ["VITE_SUPABASE_URL", "VITE_SUPABASE_PUBLISHABLE_KEY", "VITE_SUPABASE_PROJECT_ID"]) {
  defines[`import.meta.env.${key}`] = JSON.stringify(env[key] ?? "");
}

const result = await build({
  stdin: {
    contents: wrapper,
    resolveDir: root,
    sourcefile: "lovable-mcp-supabase-entry.ts",
    loader: "ts",
  },
  bundle: true,
  write: false,
  format: "esm",
  platform: "neutral",
  target: "esnext",
  absWorkingDir: root,
  logLevel: "warning",
  define: defines,
  plugins: [externalize],
});

const out = result.outputFiles[0]?.text;
if (!out) throw new Error("esbuild produced no output for the MCP function.");

const functionDir = resolve(root, "supabase/functions/mcp");
mkdirSync(functionDir, { recursive: true });
// Keep the plugin's banner first so mcpPlugin() treats this file as
// SDK-owned and regenerates it on each build; the postbuild step then
// replaces it with this correct Windows-safe bundle.
const banner =
  "// AUTO-GENERATED by @lovable.dev/mcp-js — do not edit. Regenerated by the Vite plugin.\n" +
  "// To take ownership, delete this banner line; the plugin then leaves the file alone.\n" +
  "// supabase function: mcp\n" +
  "// Bundled from src/lib/mcp/index.ts by scripts/build-mcp-function.mjs (Windows-safe).\n" +
  "// Regenerate with `npm run mcp:bundle` (runs automatically after `npm run build`).\n";
writeFileSync(resolve(functionDir, "index.ts"), banner + out);
console.log("Wrote supabase/functions/mcp/index.ts");
